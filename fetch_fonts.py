"""Self-host the Google Fonts used by SENSE: writes <out>/fonts.css + woff2 files."""
import re, sys, os, hashlib, urllib.request
out = sys.argv[1]
os.makedirs(out, exist_ok=True)
URL = ('https://fonts.googleapis.com/css2?family=Caveat:wght@500;700&family=Fraunces:opsz,ital,wght@9..144,0,500;'
       '9..144,1,500&family=Patrick+Hand&family=ZCOOL+KuaiLe&display=swap')
UA = 'Mozilla/5.0 (iPad; CPU OS 17_0 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/17.0 Mobile/15E148 Safari/604.1'
get = lambda u: urllib.request.urlopen(urllib.request.Request(u, headers={'User-Agent': UA}), timeout=30).read()
css = get(URL).decode()
urls = sorted(set(re.findall(r'url\((https://fonts\.gstatic\.com/[^)]+)\)', css)))
total = 0
for u in urls:
    data = get(u)
    name = hashlib.sha1(u.encode()).hexdigest()[:12] + os.path.splitext(u)[1]
    open(os.path.join(out, name), 'wb').write(data)
    total += len(data)
    css = css.replace(u, name)
open(os.path.join(out, 'fonts.css'), 'w').write('/* Self-hosted copy of Google Fonts (Caveat, Fraunces, Patrick Hand, ZCOOL KuaiLe; SIL OFL).\n   Generated by fetch_fonts.py, 2026-10-31. Google is unreachable from mainland China. */\n' + css)
print(len(urls), 'files', round(total/1e6, 2), 'MB')
